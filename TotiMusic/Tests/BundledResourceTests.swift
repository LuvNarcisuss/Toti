  func testFontsRegisterWithTheirOriginalNames() throws {
    _ = TotiTheme.font()
    for name in ["TetoRhythm-Text", "TetoRhythm-Display"] {
      let url = try XCTUnwrap(Bundle.main.url(forResource: name, withExtension: "ttf"))
      XCTAssertGreaterThan(try Data(contentsOf: url).count, 0)
      XCTAssertNotNil(UIFont(name: name, size: 16), name)
    }
  }

  func testAgreementsAndCreditsRemainAvailableWithoutRetiredVideos() throws {
    for document in AgreementDocument.allCases {
      let url = try XCTUnwrap(document.fileURL)
      XCTAssertTrue(try String(contentsOf: url).contains("<html"))
    }
    XCTAssertNotEqual(TotiUserAgreement.version, "unavailable")
    let credits = try XCTUnwrap(Bundle.main.url(forResource: "MediaCredits", withExtension: "json"))
    XCTAssertNoThrow(try JSONSerialization.jsonObject(with: Data(contentsOf: credits)))
    let files = try XCTUnwrap(FileManager.default.enumerator(at: Bundle.main.bundleURL,
      includingPropertiesForKeys: nil)?.allObjects as? [URL])
    XCTAssertFalse(files.contains { $0.pathExtension.lowercased() == "mp4" })
  }
